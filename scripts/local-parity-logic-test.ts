import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {serializeGridClipboard} from '../CMModelDrivenGrid/clipboard';
import {aggregateNumbers, groupRecords, groupingKey, moveColumn, numericColumnWidth, reconcileColumnOrder, choiceColorStyle} from '../CMModelDrivenGrid/gridPresentation';
import {extraDateEntries} from '../CMModelDrivenGrid/dateConditions';
import {getFilterDefinitions, updateColumnFilter, getColumnConditions, deriveFilterRule} from '../CMModelDrivenGrid/filtering';
import {appendFetchFilter} from '../CMModelDrivenGrid/childRecords';
import {needsServerFilter} from '../CMModelDrivenGrid/datasetFiltering';
import {evaluateDemoFilter} from './demo-filter-evaluator';

const dom = new JSDOM();
Object.assign(globalThis,{DOMParser:dom.window.DOMParser,XMLSerializer:dom.window.XMLSerializer});
assert.equal(serializeGridClipboard([['A','B'],['C','D']]),'A\tB\r\nC\tD');
assert.equal(serializeGridClipboard([['a\tb','c\nd','say "yes"']]),'"a\tb"\t"c\nd"\t"say ""yes"""');
assert.equal(aggregateNumbers([0,10,20,null,undefined,NaN,'999'],'sum'),30);
assert.equal(aggregateNumbers([0,10,20,null],'average'),10);
assert.equal(aggregateNumbers([0,-2,5],'minimum'),-2);
assert.equal(aggregateNumbers([0,-2,5],'maximum'),5);
assert.equal(aggregateNumbers([null,NaN],'sum'),null);
assert.equal(aggregateNumbers(Array(2000).fill(0.1),'sum'),200);
assert.deepEqual(moveColumn(['a','b','c'],0,2),['b','c','a']);
assert.deepEqual(moveColumn(['a','b'],0,-1),['a','b']);
assert.deepEqual(reconcileColumnOrder(['a','b','c'],['b','missing','b']),['b','a','c']);
assert.equal(numericColumnWidth('220'),220);
for(const width of ['','0','79','2001','1.5','NaN']) assert.throws(()=>numericColumnWidth(width));
assert.equal(choiceColorStyle('#ffffff')?.color,'#000000');
assert.equal(choiceColorStyle('#000000')?.color,'#ffffff');
assert.equal(choiceColorStyle('url(secret)'),undefined);
const grouped = groupRecords([{id:'one',label:'Same'},{id:'two',label:'Same'},{id:'one',label:'Same'}],row=>row.id,row=>row.label);
assert.deepEqual(grouped.groups.map(group=>[group.key,group.count,group.startIndex]),[['one',2,0],['two',1,2]]);
assert.notEqual(groupingKey(null), groupingKey('__blank__'));
assert.notEqual(groupingKey(null), groupingKey('null'));
assert.equal(getFilterDefinitions('DateAndTime.DateAndTime').length,53);
assert.equal(getFilterDefinitions('DateAndTime.DateOnly').length,49);
for(const [mode,[label,operator,fetchOperator,input]] of extraDateEntries) {
  const value = input === 'none' ? undefined : input === 'periodYear' ? ['3','2026'] : input === 'year' ? '2026' : '3';
  const filter = updateColumnFilter(undefined,'createdon',mode,value)!;
  const condition = getColumnConditions(filter,'createdon')[0];
  assert.equal(Number(condition.conditionOperator),operator,label);
  assert.equal(deriveFilterRule(condition)?.mode,mode,label);
  assert.ok(needsServerFilter(filter),`${label} must use server semantics`);
  const xml = new dom.window.DOMParser().parseFromString('<fetch><entity name="account"/></fetch>','text/xml');
  appendFetchFilter(xml,xml.querySelector('entity')!,filter);
  const compiled=xml.querySelector('condition')!;
  assert.equal(compiled.getAttribute('operator'),fetchOperator,label);
  if(input==='periodYear') assert.deepEqual([...compiled.querySelectorAll('value')].map(node=>node.textContent),['3','2026']);
  if(input==='none') assert.equal(compiled.hasAttribute('value'),false);
}
assert.throws(()=>updateColumnFilter(undefined,'createdon','inFiscalPeriodAndYear',['0','2026']));
assert.throws(()=>updateColumnFilter(undefined,'createdon','inFiscalYear','10000'));
for(const value of ['100% cotton','under_score','[Bracket]',"O'Brien & Sons"]) {
  const filter=updateColumnFilter(undefined,'name','contains',value)!;
  assert.equal(deriveFilterRule(getColumnConditions(filter,'name')[0])?.value,value);
  assert.ok(evaluateDemoFilter({name:value},filter,{getValue:row=>row.name}));
}
assert.equal(evaluateDemoFilter({name:'1000 cotton'},updateColumnFilter(undefined,'name','contains','100%')!,{getValue:row=>row.name}),false);
assert.equal(evaluateDemoFilter({name:'underXscore'},updateColumnFilter(undefined,'name','contains','under_score')!,{getValue:row=>row.name}),false);
const clock=new Date('2026-09-10T12:00:00Z');
const matches=(date:string,mode:Parameters<typeof updateColumnFilter>[2],value?:string|string[])=>evaluateDemoFilter({date},updateColumnFilter(undefined,'date',mode,value),{getValue:row=>row.date,now:clock});
assert.ok(matches('2026-09-14','nextWeek'));
assert.ok(matches('2026-10-01','nextMonth'));
assert.ok(matches('2027-01-01','nextYear'));
assert.ok(matches('2026-09-10T11:00:00Z','lastXHours','2'));
assert.ok(!matches('2026-09-10T09:00:00Z','lastXHours','2'));
assert.ok(matches('2026-03-10','inFiscalPeriodAndYear',['3','2026']));
assert.ok(!matches('2026-04-01','inFiscalPeriodAndYear',['3','2026']));
assert.ok(matches('2024-01-01','olderThanXYears','1'));
console.log('Parity logic passed: 30 additional date mappings, fiscal input validation, literal wildcards, grouping, aggregates, column movement/width, colour contrast and quoted Excel TSV.');
dom.window.close();
